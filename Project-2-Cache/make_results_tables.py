#!/usr/bin/env python3
"""Generates RESULTS_TABLES.md from data/raw/*.csv (+ data/processed). Numbers quoted in REPORT.md is from this file."""
import os, glob, numpy as np, pandas as pd
H = os.path.dirname(os.path.abspath(__file__)); RAW = f"{H}/data/raw"; PRO = f"{H}/data/processed"
out = ["# RESULTS_TABLES (auto-generated by make_results_tables.py; do not edit by hand)\n"]
def md(df, fmt=".3g"):
    try: return df.to_markdown(index=False, floatfmt=fmt)
    except ImportError: return "```\n" + df.to_string(index=False) + "\n```"
def load(n): p = f"{RAW}/{n}.csv"; return pd.read_csv(p) if os.path.exists(p) else None
def sec(title, body): out.extend([f"## {title}\n", body, "\n"])
fr = open(f"{RAW}/freq_estimate_ghz.txt").read().split() if os.path.exists(f"{RAW}/freq_estimate_ghz.txt") else None
F = float(fr[0]) if fr else np.nan
if fr: sec("0. Core clock estimate (used for ns -> cycles)", f"add-chain {fr[0]} GHz, imul-chain {fr[1]} GHz (they should agree within a few percent; the guest cannot read the real clock). Cycle numbers below use the add-chain value and are only as good as this estimate.")
zq = load("zero_queue")
if zq is not None:
    g = zq.groupby(["level", "huge"]).agg(lat_ns_median=("lat_ns", "median"), lat_ns_std=("lat_ns", "std"), n=("lat_ns", "count"), thp_kb=("thp_kb", "max"), ws_KiB=("ws_bytes", lambda s: s.iloc[0] / 1024)).reset_index()
    g["cycles_at_estimated_clock"] = g.lat_ns_median * F; g["level"] = pd.Categorical(g.level, ["L1", "L2", "L3", "DRAM"]); g = g.sort_values(["level", "huge"])
    sec("1. Zero-queue latency (random single-chain pointer chase)", "huge=1 requests transparent huge pages; **thp_kb must be > 0 for huge=1 rows to mean anything** (if 0, the TLB effect is NOT removed).\n\n" + md(g))
ws = load("ws_sweep")
if ws is not None:
    a = ws.groupby(["pattern", "ws_bytes"]).lat_ns.median().reset_index(); rows = []
    for pat, d in a.groupby("pattern"):
        d = d.sort_values("ws_bytes").reset_index(drop=True)
        for i in range(1, len(d)):
            r = d.lat_ns[i] / d.lat_ns[i - 1]
            if r > 1.3: rows.append(dict(pattern=pat, step_at_KiB=d.ws_bytes[i] / 1024, latency_before_ns=d.lat_ns[i - 1], latency_after_ns=d.lat_ns[i], ratio=r))
    sec("2. Working-set sweep: where latency jumps by more than 1.3x between neighbouring sizes", md(pd.DataFrame(rows)) if rows else "no step above 1.3x found")
pl, pb = load("pattern_lat"), load("pattern_bw")
if pl is not None: sec("3a. Latency, sequential vs random, by node granularity (DRAM-sized)", md(pl.groupby(["pattern", "gran"]).lat_ns.agg(["median", "std", "count"]).reset_index()))
if pb is not None: sec("3b. Bandwidth by pattern and stride (useful bytes = 64 B per touched line)", md(pb[["threads", "pattern", "stride", "bw_GBps", "Mlines_s"]]))
rw = load("rw_mix")
if rw is not None: sec("4. Read/write mix (bandwidth of the load threads, latency of a concurrent probe thread)", md(rw[["pattern", "readpct", "threads", "bw_GBps", "lat_ns"]]))
for iname, isec in (("intensity", "5"), ("intensity_seq", "5b")):
  it = load(iname)
  if it is not None:
      rows = []
      for T, g in it.groupby("threads"):
          g = g.sort_values("bw_GBps"); x, y = g.bw_GBps.values, g.lat_ns.values
          k = int(np.argmax((x - x[0]) / (x[-1] - x[0] + 1e-12) - (y - y[0]) / (y[-1] - y[0] + 1e-12))) if len(x) > 2 else 0
          infl = g.Mlines_s.values * 1e6 * y * 1e-9
          rows.append(dict(load_threads=T, unloaded_lat_ns=y.min(), max_bw_GBps=x.max(), knee_bw_GBps=x[k], knee_lat_ns=y[k], lines_in_flight_at_knee=infl[k], lines_in_flight_max=infl.max(), lat_at_max_bw_ns=y[np.argmax(x)]))
      sec(f"{isec}. [{iname}] Throughput-latency knee (Kneedle point) and Little's Law concurrency (lines in flight = lines/s x latency)", md(pd.DataFrame(rows)))
ch = load("chains")
if ch is not None:
    a = ch.groupby("chains").agg(thr_Mloads_s=("thr_Mloads_s", "median"), lat_ns=("lat_ns", "median"), lat_std=("lat_ns", "std")).reset_index(); a["lines_in_flight"] = a.thr_Mloads_s * 1e6 * a.lat_ns * 1e-9
    sec("6. Single-core memory-level parallelism: K independent chains (K = requested outstanding misses)", md(a))
cm = load("cache_miss")
if cm is not None:
    cm = cm.assign(ns_per_line=1e3 / cm.Mlines_s); g = cm.groupby(["pattern", "ws_bytes"]).agg(ns_per_line=("ns_per_line", "median"), bw_GBps=("bw_GBps", "median")).reset_index()
    note = "Hardware counters were available." if cm["L1-dcache-load-misses"].notna().any() else "**No hardware counters were available (perf unsupported): miss rates are inferred (AMAT model, section 11), not measured.**"
    sec("7. Footprint sweep, 1 thread, 64 B line operations", note + "\n\n" + md(g))
tl = load("tlb")
if tl is not None:
    tl = tl.assign(pages=tl.ws_bytes / 4096); rows = []
    for h, g in tl.groupby("huge"):
        a = g.groupby("pages").lat_ns.median()
        rows.append(dict(huge=h, thp_kb_max=g.thp_kb.max(), lat_le64pages_ns=a[a.index <= 64].median(), lat_65_to_2048_ns=a[(a.index > 64) & (a.index <= 2048)].median(), lat_gt2048_ns=a[a.index > 2048].median()))
    sec("8. TLB reach: one node per 4 KiB page, random order (L1 DTLB 64 entries, L2 DTLB 2048 entries expected for 4 KiB pages)", "**If thp_kb_max is 0 for huge=1, transparent huge pages were NOT in effect** (then the two curves should look alike).\n\n" + md(pd.DataFrame(rows)))
pp, pc = load("pitfall_pin"), load("pitfall_cachereuse")
if pp is not None:
    g = pp.groupby("mode").lat_ns.agg(["median", "std", "min", "max", "count"]).reset_index(); g["cv_pct"] = 100 * g["std"] / g["median"]; sec("9a. Pitfall: pinned vs unpinned (same benchmark, 12 processes each)", md(g))
if pc is not None: sec("9b. Pitfall: 'DRAM bandwidth' measured on buffers of increasing size (1 thread, sequential read)", md(pc[["ws_bytes", "bw_GBps"]]))
tags = {os.path.basename(f)[len("zero_queue_"):-4]: pd.read_csv(f) for f in glob.glob(f"{RAW}/zero_queue_*.csv")}
if tags and zq is not None:
    tags = {"default": zq, **tags}; rows = []
    for tg, d in tags.items():
        m = d[d.huge == 1].groupby("level").lat_ns.median()
        rows.append(dict(run=tg, **{f"{l}_ns": m.get(l, np.nan) for l in ("L1", "L2", "L3", "DRAM")}))
    sec("9c. Pitfall: same benchmark under different power settings (run tags)", md(pd.DataFrame(rows)))
xc = load("crosscheck")
if xc is not None:
    p = xc.pivot_table(index="threads", columns="tool", values="best_GBps").reset_index(); p["membw70/triad"] = p.membw70 / p.triad
    sec("10. Cross-check of membw against an independent STREAM-style triad (counted GB/s, no write-allocate counted)", md(p))
am = load("amat_model") if False else (pd.read_csv(f"{PRO}/amat_model.csv") if os.path.exists(f"{PRO}/amat_model.csv") else None)
if am is not None: sec("11. AMAT capacity model vs measured (random chase)", md(am))
open(f"{H}/RESULTS_TABLES.md", "w").write("\n".join(out)); print("wrote RESULTS_TABLES.md")
