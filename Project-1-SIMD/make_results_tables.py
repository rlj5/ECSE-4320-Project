#!/usr/bin/env python3
"""Generates RESULTS_TABLES.md from data/processed/*.csv (written by plot_all.py) and reports/*.csv.
Every number quoted in REPORT.md should be copied from RESULTS_TABLES.md."""
import os, numpy as np, pandas as pd
H = os.path.dirname(os.path.abspath(__file__)); P = f"{H}/data/processed"; R = f"{H}/reports"; RAW = f"{H}/data/raw"
L1, L2, L3 = 32 * 1024, 512 * 1024, 16 * 2**20
out = ["# RESULTS_TABLES (auto-generated by make_results_tables.py; do not edit by hand)\n"]
def md(df, **kw):
    try: return df.to_markdown(index=False, floatfmt=kw.get("floatfmt", ".3g"))
    except ImportError: return "```\n" + df.to_string(index=False) + "\n```"
def load(p): return pd.read_csv(p) if os.path.exists(p) else None
REG = {"L1 (~16 KiB)": 16 * 1024, "L2 (~256 KiB)": 256 * 1024, "L3 (~8 MiB)": 8 * 2**20, "DRAM (largest)": 10**12}
def nearest(g, target):
    g = g.assign(d=(np.log(g.ws) - np.log(min(target, g.ws.max()))).abs()); return g.loc[g.d.idxmin()]

sw = load(f"{P}/sweep_agg.csv")
if sw is not None:
    rows = []
    for (k, dt), g in sw.groupby(["kernel", "dtype"]):
        for reg, tgt in REG.items():
            base = nearest(g[g.variant == "scalar"], tgt)
            for v in ("scalar", "auto", "native", "native_fm"):
                r = nearest(g[g.variant == v], tgt)
                rows.append(dict(kernel=k, dtype=dt, regime=reg, variant=v, ws_KiB=r.ws / 1024, speedup_vs_scalar=base.t_med / r.t_med, GFLOPs=r.gflops, GiBs=r.gibs, tsc_cyc_per_elem=r.tsc_med, rel_err_pct=100 * r.rel_err))
    t = pd.DataFrame(rows); t.to_csv(f"{P}/table_speedups.csv", index=False)
    out += ["## 1. Speedup, throughput, cycles/element by regime (nearest sweep point to each target working set)\n",
            "speedup = scalar time / variant time at the same N. `tsc_cyc_per_elem` counts TSC (reference) cycles, not core cycles. `rel_err_pct` = std/median over repetitions.\n", md(t), "\n"]
al = load(f"{P}/align_agg.csv")
if al is not None:
    rows = []
    for (v, k, N), g in al.groupby(["variant", "kernel", "N"]):
        b = g[(g.offx == 0) & (g.offy == 0)].t_med.iloc[0]
        for _, r in g.iterrows(): rows.append(dict(variant=v, kernel=k, N=N, offx_B=r.offx, offy_B=r.offy, time_ratio_vs_aligned=r.t_med / b, rel_err_pct=100 * r.rel_err))
    t = pd.DataFrame(rows); t.to_csv(f"{P}/table_alignment.csv", index=False)
    out += ["## 2. Alignment: time relative to both arrays at offset 0 (>1 = slower)\nN=2048 f32 is L1-resident; N=2^22 is DRAM-resident.\n", md(t), "\n"]
tl = load(f"{P}/tail_agg.csv")
if tl is not None:
    rows = []
    for v, g in tl[tl.N <= 72].groupby("variant"):
        f = g[g.N >= 32]; a, b = np.polyfit(f.N, f.t_med * 1e9, 1); resid = (f.t_med * 1e9 - (a * f.N + b))
        small = g[g.N <= 16]
        rows.append(dict(variant=v, ns_per_elem_fit=a, fixed_cost_ns=b, resid_std_ns=resid.std(), cyc_per_elem_N1_16_min=small.tsc_med.min(), cyc_per_elem_N1_16_max=small.tsc_med.max(),
                         cyc_per_elem_N64=g[g.N == 64].tsc_med.iloc[0] if (g.N == 64).any() else np.nan))
    t = pd.DataFrame(rows); t.to_csv(f"{P}/table_tail.csv", index=False)
    r4096 = tl[tl.N >= 4096].groupby("variant").apply(lambda d: pd.Series(dict(spread_ns_over_r0_15=(d.t_med.max() - d.t_med.min()) * 1e9, median_ns=d.t_med.median() * 1e9))).reset_index()
    out += ["## 3. Tail handling\nAffine fit t(N) = a*N + b for N in 32..72 (b = fixed cost per call). Residual std shows whether an N mod 8/4 sawtooth rises above noise.\n", md(t), "\nN = 4096 + r (r = 0..15): spread of time across remainders\n", md(r4096), "\n"]
st = load(f"{P}/stride_agg.csv")
if st is not None:
    rows = []
    for (v, dt, N), g in st.groupby(["variant", "dtype", "N"]):
        s1 = g[(g.kernel == "stride") & (g.stride == 1)]
        if s1.empty: continue
        s1 = s1.iloc[0]
        for _, r in g.iterrows():
            lab = f"stride {int(r.stride)}" if r.kernel == "stride" else "gather"
            rows.append(dict(variant=v, dtype=dt, N=N, access=lab, ns_per_elem=r.t_med / r.N * 1e9, useful_GiBs=r.gibs, frac_of_stride1=r.gibs / s1.gibs))
    t = pd.DataFrame(rows); t.to_csv(f"{P}/table_stride.csv", index=False)
    out += ["## 4. Stride / gather (useful bytes = nominal 12 B/element f32, 24 B f64)\nN=4096 is cache-resident; N=2^22 is DRAM-resident (footprint grows with stride).\n", md(t), "\n"]
dt_ = load(f"{P}/dtype_compare.csv")
if dt_ is not None: out += ["## 5. Data-type comparison (median speedup of native_fm vs scalar)\n", md(dt_), "\n"]
rl, pk = load(f"{P}/roofline_params.csv"), load(f"{RAW}/peak.csv")
if pk is not None: out += ["## 6. Roofline inputs\nMeasured single-core FMA peak (best of 8, 10, or 12 independent chains) and best DRAM-size read stream.\n", md(pk), "\n"]
if rl is not None: out += [md(rl), "\n"]
if sw is not None and rl is not None:
    rows = []
    AI = {"saxpy": 2 / 12, "mul": 1 / 12, "dot": 2 / 8, "stencil": 5 / 8}
    for k, ai in AI.items():
        g = sw[(sw.kernel == k) & (sw.dtype == "f32") & (sw.variant == "native_fm")]
        if g.empty: continue
        l1, dr = nearest(g, 16 * 1024), nearest(g, 10**12); roof = min(rl.peak_f32_gflops.iloc[0], ai * rl.bw_gbs.iloc[0])
        rows.append(dict(kernel=k, AI_flop_per_byte=ai, GFLOPs_L1=l1.gflops, GFLOPs_DRAM=dr.gflops, roof_at_AI_GFLOPs=roof, pct_of_roof_DRAM=100 * dr.gflops / roof, pct_of_peak_L1=100 * l1.gflops / rl.peak_f32_gflops.iloc[0]))
    out += ["## 7. Roofline coordinates (f32, native_fm)\n", md(pd.DataFrame(rows)), "\n"]
vc, gv = load(f"{R}/vec_counts.csv"), load(f"{R}/gcc_verdicts.csv")
if gv is not None: out += ["## 8. GCC loop-vectorizer verdict per build/kernel\n", md(gv), "\n"]
if vc is not None: out += ["## 9. Instruction counts inside each kernel function (from objdump)\npacked_fp = packed FP mnemonics (ps/pd), ymm = instructions touching 256-bit registers, fma = FMA instructions.\n", md(vc), "\n"]

# Effective core clock with no cpufreq under WSL2, and assumptions with the table.
try:
    env = open(f"{H}/env/simd_env.txt").read(); import re
    bogo = float(re.search(r"BogoMIPS:\s+([0-9.]+)", env).group(1)); tsc_ghz = bogo / 2 / 1000     # Linux BogoMIPS = 2 x TSC kHz-ish; ASSUMPTION
    if sw is not None:
        rows = []
        def l1(k, dt, v):
            g = sw[(sw.kernel == k) & (sw.dtype == dt) & (sw.variant == v)]; return nearest(g, 16 * 1024)
        a = l1("dot", "f32", "scalar"); t_ns = a.tsc_med / tsc_ghz
        rows.append(dict(method="strict scalar dot chain: 1 FADD (assumed 3 cycles) per element", tsc_cyc_per_elem=a.tsc_med, ns_per_elem=t_ns, assumed_core_cycles=3.0, implied_core_GHz=3.0 / t_ns))
        b = l1("dot", "f32", "native_fm"); t_ns = b.tsc_med / tsc_ghz
        rows.append(dict(method="fast-math dot: one 8-lane vaddps chain (assumed 3 cycles per 8 elements)", tsc_cyc_per_elem=b.tsc_med, ns_per_elem=t_ns, assumed_core_cycles=3.0 / 8, implied_core_GHz=(3.0 / 8) / t_ns))
        out += [f"## 10. Effective core clock inferred from latency-bound loops\nTSC frequency assumed = BogoMIPS/2 = {tsc_ghz:.3f} GHz. FADD latency 3 cycles is an ASSUMPTION (Zen 3, not measured here). Use these only as a consistency check, not as a measured clock.\n", md(pd.DataFrame(rows)), "\n"]
except Exception as e: out += [f"## 10. clock inference skipped ({e})\n"]
# Loop placement
la, lr = load(f"{R}/loop_alignment.csv"), load(f"{RAW}/loopalign.csv")
if la is not None: out += ["## 11a. Where each hot loop starts (reports/loop_alignment.csv): crosses_64B_boundary = 1 means the loop body straddles a 64-byte line\n", md(la), "\n"]
if lr is not None:
    lr = lr.assign(ns_per_elem=lr.sec_per_call / lr.N * 1e9); g = lr.groupby(["kernel", "dtype", "variant"]).ns_per_elem.agg(["median", "std"]).reset_index()
    p = g.pivot_table(index=["kernel", "dtype"], columns="variant", values="median").reset_index()
    for base in ("scalar", "native", "native_fm"):
        if base in p and base + "_al" in p: p[f"{base}_al/{base}"] = p[base + "_al"] / p[base]
    out += ["## 11b. Loop-placement test: ns/element at N=1024 (L1-resident); `X_al` = same flags plus -falign-loops=64. A ratio far from 1 means code placement alone changes the speed.\n", md(p), "\n"]
if lr is not None:
    q = lr.groupby(["kernel", "dtype", "variant"]).ns_per_elem.median().unstack("variant")
    t = pd.DataFrame({"scalar_ns": q.scalar, "scalar_al_ns": q.scalar_al, "native_ns": q.native, "native_al_ns": q.native_al, "native_fm_ns": q.native_fm, "native_fm_al_ns": q.native_fm_al,
                      "speedup_as_built_native": q.scalar / q.native, "speedup_as_built_native_fm": q.scalar / q.native_fm,
                      "speedup_controlled_native_al": q.scalar_al / q.native_al, "speedup_controlled_native_fm_al": q.scalar_al / q.native_fm_al}).reset_index()
    t.to_csv(f"{P}/table_placement_controlled.csv", index=False)
    out += ["## 11c. SIMD speedup at N = 1024, as built (builds in the main sweep) and with every loop aligned to 64 B (`*_al`)\n", md(t), "\n"]
ls = load(f"{R}/loop_alignment_stride.csv")
if ls is not None: out += ["## 11d. Loops inside the strided kernels (which loop runs depends on the stride; all backward-branch loops are listed)\n", md(ls), "\n"]
open(f"{H}/RESULTS_TABLES.md", "w").write("\n".join(out)); print("wrote RESULTS_TABLES.md")
